def create_batch_jsonl_per_task(
    input_csv: str,
    output_dir: str,
    text_column: str = "full_text",
    case_id_column: str = "verdict",
    model: str = "gpt-4.1-mini",
    tasks_to_run: List[str] = None,  # Optional: specify which tasks to run, None = all
):
    """
    Creates one JSONL file per task/prompt type.
    
    Args:
        input_csv: Path to input CSV with verdict texts
        output_dir: Directory where JSONL files will be saved (one per task)
        text_column: Column name containing the verdict text
        case_id_column: Column name containing the case ID
        model: OpenAI model to use
        tasks_to_run: List of task names to run, or None for all tasks
    """
    df = pd.read_csv(input_csv, encoding="utf-8")
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    
    # Determine which tasks to run
    tasks_to_process = tasks_to_run if tasks_to_run else list(TASKS.keys())
    
    total_requests = 0
    created_files = []
    
    for task_name in tasks_to_process:

        if task_name not in TASKS.keys():
            print(f"⚠️ Unknown task: {task_name}, skipping...")
            print(f"\n🔍 Processing task: {task_name}")
            # print(TASKS.keys()) 
            continue
            
        task_type, builder, max_completion_tokens = TASKS[task_name]
        jsonl_file = output_path / f"{task_name}.jsonl"
        
        n_requests = 0
        with jsonl_file.open("w", encoding="utf-8") as f:
            for i, row in df.iterrows():
                verdict_text = row.get(text_column, "")
                case_id = str(row.get(case_id_column, f"row_{i}"))
                if pd.isna(verdict_text) or not str(verdict_text).strip():
                    continue

                prompt = builder(verdict_text)

                req = {
                    "custom_id": f"{case_id}__{task_name}",
                    "method": "POST",
                    "url": "/v1/chat/completions",
                    "body": {
                        "model": model,
                        "messages": [
                            {"role": "system", "content": SYSTEM_MSG},
                            {"role": "user", "content": prompt},
                        ]

                    },
                }

                f.write(json.dumps(req, ensure_ascii=False) + "\n")
                n_requests += 1
        
        total_requests += n_requests
        created_files.append((task_name, str(jsonl_file), n_requests))
        print(f"✅ Created: {jsonl_file} ({n_requests} requests)")
    
    print(f"\n📊 Summary:")
    print(f"   - Total JSONL files created: {len(created_files)}")
    print(f"   - Total requests: {total_requests}")
    print(f"   - Cases processed: {len(df)}")
    print(f"   - Output directory: {output_dir}")
    
    return created_files



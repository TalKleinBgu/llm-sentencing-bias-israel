def normalize_drug_quantity(quantity_str: str) -> str:
    if not quantity_str:
        return quantity_str
    if not isinstance(quantity_str, str):
        quantity_str = str(quantity_str)

    total_grams = 0.0
    total_tablets = 0.0
    other_units = []

    pattern = r'\[([0-9.]+)-(.*?)\]'
    matches = re.findall(pattern, quantity_str)

    for amount_str, unit in matches:
        unit = unit.strip()
        try:
            amount = float(amount_str)
        except ValueError:
            other_units.append(f"[{amount_str}-{unit}]")
            continue

        if unit in ['ק"ג', 'קילוגרם', 'קילו', 'kg']:
            total_grams += amount * 1000
        elif unit == 'גרם':
            total_grams += amount
        elif unit in ['בולים', 'כדורים', 'יחידות', 'טבליות']:
            total_tablets += amount
        else:
            other_units.append(f"[{amount_str}-{unit}]")

    parts = []
    if total_grams > 0:
        # keep as int if whole
        if total_grams == int(total_grams):
            parts.append(f"[{int(total_grams)}-גרם]")
        else:
            parts.append(f"[{total_grams}-גרם]")

    if total_tablets > 0:
        if total_tablets == int(total_tablets):
            parts.append(f"[{int(total_tablets)}-טבליות]")
        else:
            parts.append(f"[{total_tablets}-טבליות]")

    parts.extend(other_units)
    return ", ".join(parts) if parts else ""


def post_process_row(d: Dict[str, Any]) -> Dict[str, Any]:
    # 1) section_19 "כן" -> "א"
    if d.get("section_19") == "כן":
        d["section_19"] = "א"

    # 2) normalize quantities
    drug_fields = [
        'lsd', 'methamphetamine', 'ayahuasca', 'cathinone', 'ketamine',
        'hashish', 'methylmethcathinone', 'cannabis_plants', 'cannabis',
        'mdma', 'cocaine', 'heroin'
    ]
    for f in drug_fields:
        v = d.get(f, "")
        if v:
            d[f] = v

    return d

def download_and_concat_outputs_and_errors(batch_ids, out_jsonl_path: str, err_jsonl_path: str, client=None):
    ensure_dir_for_file(out_jsonl_path)
    ensure_dir_for_file(err_jsonl_path)

    with open(out_jsonl_path, "wb") as out, open(err_jsonl_path, "wb") as err:
        for bid in batch_ids:
            if client is None:
                from openai import OpenAI
                client = OpenAI()  # ייקח את ה-API key מ-os.environ
            
            batch = client.batches.retrieve(bid)

            if batch.status != "completed":
                print(f"⚠️ Skipping {bid}: {batch.status}")
                continue

            # 1) successes
            if getattr(batch, "output_file_id", None):
                content = client.files.retrieve_content(batch.output_file_id)
                content_bytes = content.encode("utf-8") if isinstance(content, str) else content
                out.write(content_bytes)
                if not content_bytes.endswith(b"\n"):
                    out.write(b"\n")
                print(f"✅ Added OUTPUT from {bid}")

            # 2) failures
            if getattr(batch, "error_file_id", None):
                content = client.files.retrieve_content(batch.error_file_id)
                content_bytes = content.encode("utf-8") if isinstance(content, str) else content
                err.write(content_bytes)
                if not content_bytes.endswith(b"\n"):
                    err.write(b"\n")
                print(f"❌ Added ERRORS from {bid}")

    print("✅ Combined output written to:", out_jsonl_path)
    print("✅ Combined errors written to:", err_jsonl_path)

def combined_jsonl_to_case_df(combined_output_jsonl: str, final_csv: str = None) -> pd.DataFrame:
    merged = {}
    skipped = 0
    errors = 0

    with open(combined_output_jsonl, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            obj = json.loads(line)

            custom_id = obj.get("custom_id", "")
            if "__" not in custom_id:
                skipped += 1
                continue

            case_id, task_name = custom_id.split("__", 1)
            merged.setdefault(case_id, {"original_case": case_id})

            resp = obj.get("response", {})
                        # בדוק שגיאות
            if resp.get("status_code") != 200:
                errors += 1
                print(f"❌ Error in {custom_id}: status {resp.get('status_code')}")
                continue

            if not resp or "body" not in resp:
                merged[case_id][task_name] = ""
                continue

            body = resp["body"]
            try:
                content = body["choices"][0]["message"]["content"]
            except Exception:
                merged[case_id][task_name] = ""
                continue

            content = strip_code_fences(content)

            # Decide if this task returned JSON (grouped) or plain text
            # Heuristic: if content looks like JSON object -> parse and update fields
            if content.lstrip().startswith("{"):
                data = safe_json_loads(content)
                if isinstance(data, dict):
                    merged[case_id].update(data)
                else:
                    merged[case_id][task_name] = content.strip()
            else:
                merged[case_id][task_name] = content.strip()

    # Post-process per case
    rows = []
    for _, row in merged.items():
        rows.append(post_process_row(row))

    df = pd.DataFrame(rows)

    if final_csv:
        ensure_dir_for_file(final_csv)
        df.to_csv(final_csv, index=False, encoding="utf-8-sig")
        print("✅ Saved CSV:", final_csv)

    print(f"📊 סטטיסטיקות:")
    print(f"   - תיקים ייחודיים: {len(merged)}")
    print(f"   - שורות שדולגו (ללא __): {skipped}")
    print(f"   - שגיאות API: {errors}")

    return df
 
